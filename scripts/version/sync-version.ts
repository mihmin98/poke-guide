/**
 * Copies the app version from package.json (the single source of truth, plan §17.1) to the places that
 * need it at runtime: the `APP_VERSION` constant and the service worker's `appData`, which the update
 * snackbar reads to name the new version. `npm version` runs it through the `version` lifecycle script.
 *
 *   npm run version:sync             write src/app/core/version.ts and ngsw-config.json
 *   npm run version:sync -- --check  fail if they don't match package.json
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

const root = process.cwd();
if (!existsSync(resolve(root, 'angular.json'))) {
  throw new Error('Run this script from the repository root (npm run version:sync).');
}

const { version } = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')) as {
  version: string;
};
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  throw new Error(`package.json version "${version}" isn't a plain MAJOR.MINOR.PATCH release.`);
}

function versionTs(): string {
  return [
    '// GENERATED by scripts/version/sync-version.ts from package.json. Do not edit; run `npm version`.',
    '',
    '/** The released app version (plan §17.1). */',
    `export const APP_VERSION = '${version}';`,
    '',
  ].join('\n');
}

async function ngswConfig(file: string): Promise<string> {
  const config = JSON.parse(readFileSync(file, 'utf8')) as Record<string, unknown>;
  // appData goes right after the schema and index, ahead of the asset groups.
  const { $schema, index, ...rest } = config;
  delete rest['appData'];
  const json = JSON.stringify({ $schema, index, appData: { version }, ...rest });
  return format(json, { ...(await resolveConfig(file)), filepath: file });
}

async function main(): Promise<void> {
  const versionFile = resolve(root, 'src/app/core/version.ts');
  const ngswFile = resolve(root, 'ngsw-config.json');
  const outputs: [string, string][] = [
    [versionFile, versionTs()],
    [ngswFile, await ngswConfig(ngswFile)],
  ];

  const check = process.argv.includes('--check');
  let stale = false;
  for (const [file, content] of outputs) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (check) {
      if (current !== content) {
        console.error(
          `${relative(root, file)} doesn't match package.json ${version}. Run \`npm run version:sync\`.`,
        );
        stale = true;
      }
    } else if (current !== content) {
      writeFileSync(file, content);
      console.log(`wrote ${relative(root, file)}`);
    } else {
      console.log(`unchanged ${relative(root, file)}`);
    }
  }
  if (stale) process.exitCode = 1;
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
