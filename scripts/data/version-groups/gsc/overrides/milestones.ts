/**
 * Gold/Silver/Crystal story milestones (plan §7.14, Phase 11 Stage E), in walkthrough order. Written from the
 * walkthrough part pages (`Walkthrough:Pokémon Gold and Silver/Part N`, `Walkthrough:Pokémon Crystal/Part N`),
 * which share their part numbers; the build cross-checks them against those pages' badges and `{{Party}}` battles.
 *
 * The post-game Kanto story (Parts 16–28, up to Red) is required; side gifts, key items, the roaming beasts, the
 * Bug-Catching Contest, the Pokégear cards and the Unown puzzles are optional (user choices, 2026-10-13). A
 * milestone that needs a later field move sits in the part where that move arrives (Lapras: Surf, Part 8).
 *
 * Ids are a contract: `milestone-numbers.json` maps them to the numbers profiles store. Never rename one;
 * retire its number below and add a new id instead.
 */
import type { GameId } from '../../../../../src/app/core/domain/models';
import type { MilestoneDefinition, RetiredMilestone } from '../../../core/milestone-numbers';

const all = (part: number): Partial<Record<GameId, number>> => ({
  gold: part,
  silver: part,
  crystal: part,
});
const goldSilver = (part: number): Partial<Record<GameId, number>> => ({
  gold: part,
  silver: part,
});
const crystal = (part: number): Partial<Record<GameId, number>> => ({ crystal: part });

const gym = (
  leader: string,
  badge: string,
  tm: string | null,
  locationId: string,
  part: number,
): MilestoneDefinition => ({
  id: `gym-${leader.toLowerCase().replace(/[^a-z]+/g, '-')}`,
  label: `Defeat ${leader}`,
  kind: 'gym',
  part: all(part),
  locationId,
  detail: tm ? `${badge} Badge · ${tm}` : `${badge} Badge`,
  badge,
});

const rival = (
  n: number,
  locationId: string,
  part: number,
  detail: string,
): MilestoneDefinition => ({
  id: `rival-${n}`,
  label: `Rival battle ${n}`,
  kind: 'battle',
  part: all(part),
  locationId,
  detail,
});

const unownPuzzle = (pokemon: string, part: number, detail: string): MilestoneDefinition => ({
  id: `unown-puzzle-${pokemon.toLowerCase().replace(/[^a-z]+/g, '-')}`,
  label: `Solve the ${pokemon} puzzle`,
  kind: 'event',
  part: all(part),
  locationId: 'ruins-of-alph',
  detail,
  optional: true,
});

